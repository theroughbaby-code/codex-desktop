const namespaceName = 'Loupedeck.CodexDesktopPlugin';

function escapeCsharp(text) {
  return text.replaceAll('\\', '\\\\').replaceAll('"', '\\"');
}

function modifierExpression(modifiers) {
  return modifiers.length
    ? modifiers.map((modifier) => `ModifierKey.${modifier}`).join(' | ')
    : 'ModifierKey.None';
}

