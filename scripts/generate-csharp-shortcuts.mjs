function renderSvg(action, symbol = false) {
  const glyph = glyphFor(action);
  if (symbol) {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="-1 -1 26 26">
  <g fill="none" stroke="#202428" stroke-width="1.44" stroke-linecap="round" stroke-linejoin="round" color="#202428">${glyph}</g>
</svg>\n`;
  }

  return `<svg xmlns="http://www.w3.org/2000/svg" width="144" height="144" viewBox="-1 -1 26 26">
  <g fill="none" stroke="#15191d" stroke-width="2.72" stroke-linecap="round" stroke-linejoin="round" color="#15191d">${glyph}</g>
  <g fill="none" stroke="#f5f7f3" stroke-width="1.44" stroke-linecap="round" stroke-linejoin="round" color="#f5f7f3">${glyph}</g>
</svg>\n`;
}

async function syncDirectory(directory) {
  await mkdir(directory, { recursive: true });
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith('.svg') && !keep.has(entry.name)) {
      await rm(path.join(directory, entry.name));
    }
  }
}

await syncDirectory(actionIconDir);
await syncDirectory(actionSymbolDir);
await mkdir(editableActionIconDir, { recursive: true });
await mkdir(editableActionSymbolDir, { recursive: true });

for (const action of allActions) {
  const fileName = `${namespaceName}.${action.className}.svg`;
  const editableIconPath = path.join(editableActionIconDir, fileName);
  const editableSymbolPath = path.join(editableActionSymbolDir, fileName);

  if (!await fileExists(editableIconPath)) {
    await writeFile(editableIconPath, renderSvg(action));
  }

  if (!await fileExists(editableSymbolPath)) {
    await writeFile(editableSymbolPath, renderSvg(action, true));
  }

  await copyFile(editableIconPath, path.join(actionIconDir, fileName));
  await copyFile(editableSymbolPath, path.join(actionSymbolDir, fileName));
}

console.log(`Generated ${catalog.length} native shortcut classes and ${allActions.length} semantic SVG icon pairs.`);

async function fileExists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}
