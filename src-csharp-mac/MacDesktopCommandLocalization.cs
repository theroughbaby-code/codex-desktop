    public static Boolean TryParseProductModeTrigger(
        IEnumerable<String> labels,
        out String currentModeName)
    {
        const String placeholder = "{mode}";
        foreach (var value in labels)
        {
            var label = value.Trim().Replace('\u00a0', ' ');
            foreach (var sourceTemplate in ProductModeTriggerTemplates)
            {
                var template = sourceTemplate.Replace('\u00a0', ' ');
                var placeholderIndex = template.IndexOf(
                    placeholder,
                    StringComparison.Ordinal);
                if (placeholderIndex < 0)
                {
                    continue;
                }

                var prefix = template[..placeholderIndex];
                var suffix = template[(placeholderIndex + placeholder.Length)..];
                if (!label.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)
                    || !label.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                var modeLength = label.Length - prefix.Length - suffix.Length;
                if (modeLength <= 0)
                {
                    continue;
                }

                currentModeName = label.Substring(prefix.Length, modeLength).Trim();
                if (currentModeName.Length > 0)
                {
                    return true;
                }
            }
        }

        currentModeName = String.Empty;
        return false;
    }

    private static Boolean HasLocalizedLabel(
        IEnumerable<String> values,
        IReadOnlySet<String> candidates)
        => values.Any(value => candidates.Contains(value.Trim()));

